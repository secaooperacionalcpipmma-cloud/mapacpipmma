/**
 * Calculations derived strictly and dynamically from the official data.
 */
export function getCPIStats(): CPIStats {
  let totalUnidades = 0;
  let totalBatalhoes = 0;
  let totalUnidadesEspeciais = 0;
  let totalMunicipios = 0;
  let unidadesComFT = 0;
  let unidadesComGOE = 0;
  let efetivoTotalFT = 0;
  let efetivoTotalGOE = 0;

  CPAI_DATA.forEach((cpai) => {
    cpai.batalhoes.forEach((bat) => {
      totalUnidades++;
      if (bat.tipo === 'BPM') {
        totalBatalhoes++;
      } else {
        totalUnidadesEspeciais++;
      }

      totalMunicipios += bat.municipios.length;

      if (bat.ft) {
        unidadesComFT++;
        efetivoTotalFT += bat.efetivoFT;
      }

      if (bat.goe) {
        unidadesComGOE++;
        efetivoTotalGOE += bat.efetivoGOE;
      }
    });
  });

  return {
    totalCPAI: CPAI_DATA.length,
    totalUnidades,
    totalBatalhoes,
    totalUnidadesEspeciais,
    totalMunicipios,
    unidadesComFT,
    unidadesComGOE,
    efetivoTotalFT,
    efetivoTotalGOE,
  };
}
